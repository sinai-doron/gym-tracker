#!/usr/bin/env python3
"""Writes the body map the exercise picker draws, from react-native-body-highlighter (MIT).

    npm pack react-native-body-highlighter@3.2.0   # in an empty folder
    tar xzf react-native-body-highlighter-3.2.0.tgz
    python3 -I scripts/build_body_map.py path/to/package

Copies the male front and back figures (their outlines and every part's paths, left and right
sides merged) into app/src/main/assets/body_map/body_map.json, and the package's licence beside
it, which the Open-source licences screen shows. Only path strings are taken; nothing from the
package runs.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/body_map"

# Path data is numbers and SVG commands only
PATH = re.compile(r"^[MmLlHhVvCcSsQqTtAaZz0-9 .,eE+-]+$")


def strings(text: str) -> list[str]:
    found = re.findall(r'"([^"\\]*)"', text)
    for s in found:
        if not PATH.match(s):
            raise SystemExit(f"not path data: {s[:60]}")
    return found


def parts(js: Path) -> list[dict]:
    text = js.read_text()
    result = []
    # Each part is `slug: "...", color: "...", path: { left: [...], right: [...], common: [...] }`
    for chunk in re.split(r"\n\s*\{\s*\n\s*slug:", text)[1:]:
        slug = re.match(r'\s*"([a-z-]+)"', chunk).group(1)
        paths = []
        for side in re.finditer(r"(left|right|common):\s*\[(.*?)\]", chunk, re.S):
            paths += strings(side.group(2))
        if not paths:
            raise SystemExit(f"{js.name}: {slug} has no paths")
        result.append({"slug": slug, "paths": paths})
    return result


def outline(wrapper: Path, side: str) -> str:
    text = wrapper.read_text()
    match = re.search(r'side === "' + side + r'" && \(<[^>]*?d="([^"]+)"', text, re.S)
    if not match:
        raise SystemExit(f"no {side} outline in {wrapper.name}")
    return strings(f'"{match.group(1)}"')[0]


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    package = Path(sys.argv[1])
    meta = json.loads((package / "package.json").read_text())
    if meta["name"] != "react-native-body-highlighter" or meta["license"] != "MIT":
        raise SystemExit("expected react-native-body-highlighter under MIT")
    dist = package / "dist"
    wrapper = dist / "components/SvgMaleWrapper.js"
    body_map = {
        "comment": "Generated by scripts/build_body_map.py; do not edit.",
        "source": {
            "name": meta["name"],
            "version": meta["version"],
            "license": meta["license"],
            "url": "https://github.com/HichamELBSI/react-native-body-highlighter",
        },
        "views": {
            # The back figure is drawn beside the front one, so its view box starts at x 724
            "front": {"viewBox": [0, 0, 724, 1448], "outline": outline(wrapper, "front"), "parts": parts(dist / "assets/bodyFront.js")},
            "back": {"viewBox": [724, 0, 724, 1448], "outline": outline(wrapper, "back"), "parts": parts(dist / "assets/bodyBack.js")},
        },
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "body_map.json").write_text(json.dumps(body_map, indent=1) + "\n")
    (OUT / "LICENSE.txt").write_text((package / "LICENSE").read_text())
    for view, data in body_map["views"].items():
        print(view, len(data["parts"]), "parts:", ", ".join(p["slug"] for p in data["parts"]))


if __name__ == "__main__":
    main()
